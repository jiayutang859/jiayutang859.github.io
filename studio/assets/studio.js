/* ==========================================================================
   Jiayu Tang — Studio
   Reads window.STUDIO_DATA (generated by build.py), lays the current gallery
   out in justified rows, and runs the lightbox.

   Which gallery a page shows comes from <body data-gallery="...">.
   ========================================================================== */

(function () {
  "use strict";

  var DATA = window.STUDIO_DATA || [];
  var body = document.body;
  var galleryId = body.dataset.gallery;
  var mount = document.getElementById("rows");
  if (!mount) return;

  // Paths in frames.js are relative to the site root. Pages in a subfolder set
  // data-base=".." so the same data file works from any depth — and so the
  // whole site still works if you drop it under a subpath rather than a domain.
  var BASE = body.dataset.base || ".";
  function url(src) { return BASE.replace(/\/$/, "") + "/" + src; }

  // The line printed under each frame, e.g.
  //   Sony ILCE-7M4, FE 35mm F1.8, f/3.2 at 1/125, ISO 250
  // Any field the file doesn't carry is simply left out.
  function specLine(f) {
    var parts = [];
    if (f.camera) parts.push(f.camera);
    if (f.lens) parts.push(f.lens);
    else if (f.focal) parts.push(f.focal);
    if (f.aperture && f.shutter) parts.push(f.aperture + " at " + f.shutter);
    else if (f.aperture) parts.push(f.aperture);
    else if (f.shutter) parts.push(f.shutter);
    if (f.iso) parts.push(f.iso);
    return parts.join(", ");
  }

  var block = DATA.filter(function (g) { return g.id === galleryId; })[0];
  var frames = (block && block.frames) || [];

  // ---------------------------------------------------------------- header

  var countEl = document.getElementById("count");
  if (countEl) {
    countEl.textContent = frames.length
      ? frames.length + (frames.length === 1 ? " frame" : " frames")
      : "";
  }

  if (!frames.length) {
    var empty = document.createElement("p");
    empty.className = "empty";
    empty.textContent = "Nothing here yet";
    mount.appendChild(empty);
    return;
  }

  // ------------------------------------------------------- justified rows

  // Target row height as a fraction of viewport width, so rows stay in
  // proportion on wide monitors instead of turning into a thin strip.
  function targetRatio() {
    var w = mount.clientWidth || window.innerWidth;
    var rowHeight = w < 900 ? w * 0.52 : Math.max(300, Math.min(w * 0.30, 460));
    return w / rowHeight;
  }

  // Greedy packing: add frames to a row until its combined aspect ratio
  // reaches the target, then close the row. Same idea as a justified text
  // line, with aspect ratio standing in for word width.
  function pack(list, target) {
    var rows = [];
    var row = [];
    var sum = 0;
    list.forEach(function (f, i) {
      row.push({ frame: f, index: i });
      sum += f.ratio;
      if (sum >= target) {
        rows.push(row);
        row = [];
        sum = 0;
      }
    });
    if (row.length) rows.push(row);
    return rows;
  }

  function buildTile(entry, rowHeight) {
    var f = entry.frame;

    var fig = document.createElement("figure");
    fig.className = "tile";
    fig.id = galleryId + "-" + String(entry.index + 1).padStart(2, "0");

    if (rowHeight) {
      // Orphan row: don't stretch it. A lone 3:2 frame grown to full width
      // would tower over every row above it. Fix each tile at the target
      // height instead and let the row sit short, left-aligned.
      fig.style.flexGrow = "0";
      fig.style.flexShrink = "0";
      fig.style.flexBasis = Math.round(f.ratio * rowHeight) + "px";
    } else {
      // flex-grow proportional to ratio makes every tile in a row share a
      // height. Set as longhands rather than the `flex` shorthand — some
      // engines don't round-trip a fractional shorthand cleanly.
      fig.style.flexGrow = String(f.ratio);
      fig.style.flexShrink = "1";
      fig.style.flexBasis = "0";
    }
    // Used by the mobile stylesheet, which stacks rows and needs a real ratio.
    fig.style.setProperty("--r", f.ratio);

    var btn = document.createElement("button");
    btn.className = "well";
    btn.type = "button";
    btn.dataset.index = entry.index;
    // The well carries the ratio so every tile in a row lands on the same
    // image height, with the caption strip hanging below it.
    btn.style.aspectRatio = String(f.ratio);
    btn.setAttribute(
      "aria-label",
      "Open frame " + (entry.index + 1) + " of " + frames.length +
        (f.caption ? ": " + f.caption : "")
    );

    var img = document.createElement("img");
    img.loading = "lazy";
    img.decoding = "async";
    img.width = f.w;
    img.height = f.h;
    img.alt = f.caption || "";
    img.src = url(f.src);
    img.addEventListener("load", function () { img.classList.add("ready"); });
    if (img.complete) img.classList.add("ready");

    btn.appendChild(img);
    fig.appendChild(btn);

    var spec = specLine(f);
    if (f.caption || spec) {
      var cap = document.createElement("figcaption");
      cap.className = "tag";
      if (f.caption) {
        var desc = document.createElement("span");
        desc.className = "desc";
        desc.textContent = f.caption;
        cap.appendChild(desc);
      }
      if (spec) {
        var sp = document.createElement("span");
        sp.className = "spec";
        sp.textContent = spec;
        cap.appendChild(sp);
      }
      fig.appendChild(cap);
    }

    return fig;
  }

  var lastTarget = null;

  function render() {
    var target = targetRatio();
    // Re-pack only when the target has moved enough to change the layout.
    if (lastTarget !== null && Math.abs(target - lastTarget) < 0.15) return;
    lastTarget = target;

    var rows = pack(frames, target);
    var frag = document.createDocumentFragment();
    var width = mount.clientWidth || window.innerWidth;
    var rowHeight = width / target;

    rows.forEach(function (row, i) {
      var el = document.createElement("div");
      el.className = "row";

      // A trailing row that never reached the target ratio is an orphan.
      var sum = row.reduce(function (a, e) { return a + e.frame.ratio; }, 0);
      var orphan = i === rows.length - 1 && sum < target * 0.92;
      if (orphan) el.classList.add("partial");

      row.forEach(function (entry) {
        el.appendChild(buildTile(entry, orphan ? rowHeight : 0));
      });
      frag.appendChild(el);
    });

    mount.textContent = "";
    mount.appendChild(frag);
  }

  render();

  var resizeTimer;
  window.addEventListener("resize", function () {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(render, 180);
  });

  // ------------------------------------------------------------- lightbox

  var box = document.getElementById("lightbox");
  if (!box) return;

  var boxImg = document.getElementById("lbimg");
  var boxPos = document.getElementById("lbpos");
  var boxText = document.getElementById("lbtext");
  var boxMeta = document.getElementById("lbmeta");
  var btnPrev = document.getElementById("lbprev");
  var btnNext = document.getElementById("lbnext");
  var btnInfo = document.getElementById("lbinfo");
  var btnClose = document.getElementById("lbclose");

  var at = 0;
  var lastFocus = null;
  var metaOpen = false;

  // Order matters: this is the reading order in the info strip.
  var META_FIELDS = ["camera", "lens", "focal", "aperture", "shutter", "iso", "date"];

  function paintMeta(f) {
    boxMeta.textContent = "";
    META_FIELDS.forEach(function (key) {
      if (!f[key]) return;
      var span = document.createElement("span");
      span.textContent = f[key];
      boxMeta.appendChild(span);
    });
    boxMeta.classList.toggle("open", metaOpen && boxMeta.children.length > 0);
    btnInfo.setAttribute("aria-pressed", String(metaOpen));
    btnInfo.disabled = boxMeta.children.length === 0;
  }

  function show(i) {
    if (i < 0 || i >= frames.length) return;
    at = i;
    var f = frames[i];

    boxImg.src = url(f.src);
    boxImg.alt = f.caption || "";
    boxPos.textContent = (i + 1) + " / " + frames.length;
    boxText.textContent = f.caption || "";
    paintMeta(f);

    btnPrev.disabled = i === 0;
    btnNext.disabled = i === frames.length - 1;

    if (!box.hasAttribute("open")) {
      lastFocus = document.activeElement;
      box.setAttribute("open", "");
      body.style.overflow = "hidden";
      btnClose.focus();
    }
    history.replaceState(null, "", "#" + galleryId + "-" + String(i + 1).padStart(2, "0"));
  }

  function hide() {
    box.removeAttribute("open");
    body.style.overflow = "";
    boxImg.removeAttribute("src");
    history.replaceState(null, "", location.pathname + location.search);
    if (lastFocus && lastFocus.focus) lastFocus.focus();
  }

  mount.addEventListener("click", function (e) {
    var btn = e.target.closest("button[data-index]");
    if (btn) show(Number(btn.dataset.index));
  });

  btnPrev.addEventListener("click", function () { show(at - 1); });
  btnNext.addEventListener("click", function () { show(at + 1); });
  btnClose.addEventListener("click", hide);
  btnInfo.addEventListener("click", function () {
    metaOpen = !metaOpen;
    paintMeta(frames[at]);
  });

  document.addEventListener("keydown", function (e) {
    if (!box.hasAttribute("open")) return;
    if (e.key === "Escape") { hide(); return; }
    if (e.key === "ArrowLeft") { show(at - 1); return; }
    if (e.key === "ArrowRight") { show(at + 1); return; }
    if (e.key === "i" || e.key === "I") {
      metaOpen = !metaOpen;
      paintMeta(frames[at]);
      return;
    }
    // Keep tab focus inside the dialog while it is open.
    if (e.key === "Tab") {
      var stops = [btnInfo, btnPrev, btnNext, btnClose].filter(function (b) {
        return !b.disabled;
      });
      if (!stops.length) return;
      var i = stops.indexOf(document.activeElement);
      e.preventDefault();
      var next = e.shiftKey ? i - 1 : i + 1;
      if (next < 0) next = stops.length - 1;
      if (next >= stops.length) next = 0;
      stops[next].focus();
    }
  });

  // Swipe on touch devices.
  var touchX = null;
  box.addEventListener("touchstart", function (e) {
    touchX = e.changedTouches[0].clientX;
  }, { passive: true });
  box.addEventListener("touchend", function (e) {
    if (touchX === null) return;
    var dx = e.changedTouches[0].clientX - touchX;
    if (Math.abs(dx) > 48) show(dx < 0 ? at + 1 : at - 1);
    touchX = null;
  }, { passive: true });

  // Deep link: /2026/#2026-03 opens that frame directly.
  if (location.hash) {
    var m = location.hash.match(/-(\d+)$/);
    if (m) {
      var idx = Number(m[1]) - 1;
      if (idx >= 0 && idx < frames.length) show(idx);
    }
  }
})();
